#define _CRT_SECURE_NO_WARNINGS
# include <stdio.h>
int main() {
    int i = 10;
    // int* p = &i; // 不推荐这种写法，推荐将 *和变量名写在一次
    
    // int *p;
    // &运算符出现在非定义语句里面，表示取地址的意思
    // p = &i; // p里面存储的地址值是i的地址，p指向i
    // 对指针变量赋值可以修改指针的指向

    int *p = &i; //定义一个指针变量p，初始化为指向i
    printf("*p = %d\n", *p); 
    // *号运算符在定义语句里面，用来说明创建指针变量；
    //如果出现在非定义语句里面，接引用/间接访问，根据指针变量里面存储的地址和指针变量的基类型，去访问目标的内容
    *p = 11;
    printf("i = %d\n", i);
    return 0;
}