#include <stdio.h>
//开头的指令叫预处理指令
int main() {
    /*
    # 函数的定义
    # 定义:将一个概念的所有信息都描述清楚
    # -返回值 类似于数学上的因变量
    # -函数名，名字为main的函数比较特殊，它是整个程序的入口
    # -参数 类似于数学上的自变量
    # -函数体
    int 是一个关键字，它描述的是一种整数的数据类型
    main函数的返回值是一个整数
    ()说明main函数的参数是空的
    */
    int i = 1;
    //分号说明一个表达式的结束。定义了一个名字为i的变量，类型为整数。变量一创建数值就是1
    //变量就是在存储器里找了一个位置，给它起了个名字
    i = i + 2;
    //先计算i+2，再赋值给变量i，=是赋值的意思
    i = i + 3;
    i = i - 4;
    printf("i = %d\n", i);
    return 0;//返回一个整数0
}